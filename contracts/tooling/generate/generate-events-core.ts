/**
 * Pure logic of the event catalog generator: naming, catalog rules and the generated module.
 * File I/O and json-schema-to-typescript live in generate-events.ts and event-files.ts.
 */

/** `<entity>.<action>/v<N>.schema.json`, relative to contracts/events. */
const EVENT_FILE = /^([a-z]+(?:-[a-z]+)*\.[a-z]+(?:-[a-z]+)*)\/v([1-9][0-9]*)\.schema\.json$/;

/** Property names that usually carry personal data. Events carry identifiers and dates only. */
export const PERSONAL_DATA_NAMES = [
  'name',
  'firstname',
  'lastname',
  'fullname',
  'email',
  'phone',
  'address',
  'birthdate',
  'document',
  'taxid',
  'ssn',
] as const;

export type JsonSchema = Record<string, unknown>;

/** `loan.created/v1.schema.json` → `loan.created.v1`; anything else is not a catalog file. */
export const eventNameFromFile = (file: string): string | undefined => {
  const match = EVENT_FILE.exec(file);
  return match ? `${String(match[1])}.v${String(match[2])}` : undefined;
};

/** `loan.created.v1` → `LoanCreatedV1` (type and schemas) and `LOAN_CREATED_V1` (name). */
export const identifiers = (name: string): { pascal: string; constant: string } => {
  const words = name.split(/[.-]/);
  return {
    pascal: words.map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join(''),
    constant: words.map((word) => word.toUpperCase()).join('_'),
  };
};

const propertyNames = (schema: unknown): string[] => {
  if (typeof schema !== 'object' || schema === null) return [];
  if (Array.isArray(schema)) return schema.flatMap(propertyNames);
  const node = schema as JsonSchema;
  const own =
    typeof node['properties'] === 'object' && node['properties'] !== null
      ? Object.keys(node['properties'])
      : [];
  return [...own, ...Object.values(node).flatMap(propertyNames)];
};

/** Every rule of contracts/events/README.md that can be checked on a single file. */
export const checkEventSchema = (name: string, schema: JsonSchema): string[] => {
  const problems: string[] = [];
  if (schema['$id'] !== `urn:acme:event:${name}`)
    problems.push(`$id must be urn:acme:event:${name}`);
  if (schema['title'] !== name) problems.push(`title must be ${name}`);
  if (typeof schema['description'] !== 'string' || schema['description'].length === 0) {
    problems.push('description is required');
  }
  if (typeof schema['x-source'] !== 'string')
    problems.push('x-source (EventBridge source) is required');
  if (schema['type'] !== 'object') problems.push('type must be object');
  if (schema['additionalProperties'] !== false) {
    problems.push('additionalProperties must be false (producers publish the exact shape)');
  }
  const personal = propertyNames(schema).filter((property) =>
    (PERSONAL_DATA_NAMES as readonly string[]).includes(property.toLowerCase()),
  );
  for (const property of new Set(personal)) {
    problems.push(`property "${property}" looks like personal data`);
  }
  return problems;
};

/** The module generated for one event. `typeSource` is the interface json-schema-to-typescript wrote. */
export const renderEventModule = (
  file: string,
  name: string,
  schema: JsonSchema,
  typeSource: string,
): string => {
  const { pascal, constant } = identifiers(name);
  const json = JSON.stringify(schema, null, 2);
  return `/**
 * Generated from contracts/events/${file} by contracts/tooling/generate/generate-events.ts.
 * Do not edit: change the catalog (a new version for a new shape) and run \`contracts:generate\`.
 */
import { z } from 'zod';

/** Event name, used as the EventBridge \`detail-type\`. */
export const ${constant} = ${JSON.stringify(name)};

/** EventBridge \`source\` of this event. */
export const ${constant}_SOURCE = ${JSON.stringify(schema['x-source'])};

export const ${pascal}JsonSchema: z.core.JSONSchema.JSONSchema = ${json};

${typeSource.trim()}

/** Exact shape: what producers publish (their tests parse with it). */
export const ${pascal} = z.fromJSONSchema(${pascal}JsonSchema) as unknown as z.ZodType<${pascal}>;

/** Tolerant shape: what consumers parse, ignoring fields they do not know. */
export const ${pascal}Tolerant = z.fromJSONSchema({
  ...${pascal}JsonSchema,
  additionalProperties: true,
}) as unknown as z.ZodType<${pascal}>;
`;
};

export const renderIndex = (modules: readonly string[]): string =>
  `// Generated by contracts/tooling/generate/generate-events.ts. Do not edit.\n${modules
    .map((module) => `export * from './${module}';`)
    .join('\n')}\n`;
