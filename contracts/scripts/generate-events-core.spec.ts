import {
  checkEventSchema,
  eventNameFromFile,
  identifiers,
  renderEventModule,
  renderIndex,
} from './generate-events-core.ts';

const valid = {
  $id: 'urn:acme:event:loan.created.v1',
  title: 'loan.created.v1',
  description: 'A book was lent.',
  'x-source': 'acme.library',
  type: 'object',
  additionalProperties: false,
  properties: { loanId: { type: 'string' } },
};

describe('eventNameFromFile', () => {
  it.each([
    ['loan.created.v1.json', 'loan.created.v1'],
    ['book-copy.marked-lost.v12.json', 'book-copy.marked-lost.v12'],
  ])('reads %s', (file, name) => {
    expect(eventNameFromFile(file)).toBe(name);
  });

  it.each([
    'loan.created.json',
    'loan.created.v0.json',
    'Loan.created.v1.json',
    'loan_created.v1.json',
  ])('rejects %s', (file) => {
    expect(eventNameFromFile(file)).toBeUndefined();
  });
});

describe('identifiers', () => {
  it('derives the type and constant names', () => {
    expect(identifiers('book-copy.marked-lost.v2')).toEqual({
      pascal: 'BookCopyMarkedLostV2',
      constant: 'BOOK_COPY_MARKED_LOST_V2',
    });
  });
});

describe('checkEventSchema', () => {
  it('accepts a schema that follows the catalog rules', () => {
    expect(checkEventSchema('loan.created.v1', valid)).toEqual([]);
  });

  it('reports every broken rule', () => {
    expect(checkEventSchema('loan.created.v1', { properties: {} })).toEqual([
      '$id must be urn:acme:event:loan.created.v1',
      'title must be loan.created.v1',
      'description is required',
      'x-source (EventBridge source) is required',
      'type must be object',
      'additionalProperties must be false (producers publish the exact shape)',
    ]);
    expect(checkEventSchema('loan.created.v1', { ...valid, description: '' })).toEqual([
      'description is required',
    ]);
  });

  it('rejects property names that look like personal data, at any depth', () => {
    const schema = {
      ...valid,
      properties: {
        loanId: { type: 'string' },
        borrower: { type: 'object', properties: { Email: { type: 'string' } } },
        items: { type: 'array', items: [{ properties: { phone: {} } }] },
        tags: { properties: null },
      },
    };

    expect(checkEventSchema('loan.created.v1', schema)).toEqual([
      'property "Email" looks like personal data',
      'property "phone" looks like personal data',
    ]);
  });
});

describe('renderEventModule', () => {
  it('writes the constants, the JSON Schema, the type and both zod schemas', () => {
    const source = renderEventModule(
      'loan.created.v1.json',
      'loan.created.v1',
      valid,
      'export interface LoanCreatedV1 {\n  loanId?: string;\n}\n',
    );

    expect(source).toContain('Generated from contracts/events/loan.created.v1.json');
    expect(source).toContain('export const LOAN_CREATED_V1 = "loan.created.v1";');
    expect(source).toContain('export const LOAN_CREATED_V1_SOURCE = "acme.library";');
    expect(source).toContain(
      'export const LoanCreatedV1JsonSchema: z.core.JSONSchema.JSONSchema = {',
    );
    expect(source).toContain('export interface LoanCreatedV1 {\n  loanId?: string;\n}\n\n/**');
    expect(source).toContain(
      'export const LoanCreatedV1 = z.fromJSONSchema(LoanCreatedV1JsonSchema)',
    );
    expect(source).toContain('additionalProperties: true,');
  });
});

describe('renderIndex', () => {
  it('re-exports every module', () => {
    expect(renderIndex(['loan-created-v1', 'loan-returned-v1'])).toBe(
      "// Generated by contracts/scripts/generate-events.ts. Do not edit.\nexport * from './loan-created-v1';\nexport * from './loan-returned-v1';\n",
    );
  });
});
